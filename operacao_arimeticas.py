# Define dois números para operações
a = 10
b = 3

# Soma
soma = a + b

# Subtração
subtracao = a - b

# Multiplicação
multiplicacao = a * b

# Divisão real
divisao = a / b

# Divisão inteira
divisao_inteira = a // b

# Resto da divisão
resto = a % b

# Potência
potencia = a ** b

print(soma, subtracao, multiplicacao, divisao, divisao_inteira, resto, potencia)
