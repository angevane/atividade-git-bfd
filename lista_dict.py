# Cria uma lista
frutas = ["maçã", "banana"]

# Adiciona item
frutas.append("laranja")

# Atualiza item pelo índice
frutas[0] = "uva"

# Remove item
frutas.remove("banana")

print(frutas)

# Cria um dicionário
aluno = {"nome": "Carlos", "idade": 20}

# Adiciona nova chave
aluno["curso"] = "Python"

# Atualiza valor
aluno["idade"] = 21

# Remove chave
del aluno["nome"]

print(aluno)
