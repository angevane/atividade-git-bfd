# Declara uma variável do tipo inteiro
idade = 25

# Declara uma variável do tipo float
altura = 1.75

# Declara uma variável do tipo string
nome = "Ana"

# Declara uma variável do tipo booleano
estudante = True

# Converte o valor float para inteiro
# A parte decimal é truncada (não ocorre arredondamento)
altura_inteira = int(altura)

# Exibe os valores no console
print(idade, altura, nome, estudante, altura_inteira)
